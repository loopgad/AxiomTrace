/* Slice-by-4: four bytes per step with independent table lookups instead of
 * the serial crc->index->table chain of the byte-wise loop. Bit-exact with
 * the byte-wise implementation (exhaustively verified over all 65536 initial
 * states and a bitwise third-party oracle); test_crc_slice4 locks the
 * equivalence into CI. */
uint16_t axiom_crc16(const uint8_t *data, size_t len) {
    uint16_t crc = 0xFFFFu;
    size_t i = 0u;
    while (len - i >= 4u) {
        crc = (uint16_t)(axiom_crc16_slice_mh[crc >> 8] ^
                         axiom_crc16_slice_ml[crc & 0xFFu] ^
                         axiom_crc16_slice_t3[data[i]] ^
                         axiom_crc16_slice_t2[data[i + 1u]] ^
                         axiom_crc16_slice_t1[data[i + 2u]] ^
                         axiom_crc16_table[data[i + 3u]]);
        i += 4u;
    }
    for (; i < len; ++i) {
        crc = axiom_crc16_update(crc, data[i]);
    }
    return crc;
}

